/**
 * Parse an InsightApiError into a RateLimitInfo object.
 * Returns undefined for non-rate-limit/non-auth errors.
 */
function parseApiError(err: unknown): RateLimitInfo | undefined {
  if (!(err instanceof InsightApiError)) return undefined;

  const h = err.responseHeaders;
  const tier = h['x-aether-tier'] ?? 'unknown';

  if (err.status === 429) {
    const dailyLimit = h['x-aether-daily-limit'] ? parseInt(h['x-aether-daily-limit'], 10) : undefined;
    const dailyRemaining = h['x-aether-daily-remaining'] ? parseInt(h['x-aether-daily-remaining'], 10) : undefined;
    const resetsAt = h['x-aether-daily-reset'] ?? undefined;

    const dailyUsed = dailyLimit !== undefined && dailyRemaining !== undefined
      ? dailyLimit - dailyRemaining
      : undefined;

    return {
      tier,
      dailyUsed,
      dailyLimit,
      resetsAt,
      message: err.detail.includes('Daily free tier')
        ? `${err.detail} Upgrade at https://allchemy.io/pricing`
        : `Rate limit exceeded. ${err.detail}`,
    };
  }

  if (err.status === 403) {
    return {
      tier,
      expired: h['x-aether-expired'] ?? undefined,
      message: err.detail,
    };
  }

  if (err.status === 401) {
    return {
      tier: 'none',
      message: 'Invalid API key. Set ALLCHEMY_API_KEY with a valid key from https://beta.allchemylabs.ai (sign in with GitHub to get or rotate one)',
    };
  }

  return undefined;
}

/**
 * Generate a template-based fix (local, no API call).
 */
function getTemplateFix(
  req: FixRequest,
  metadata: ReturnType<typeof getRuleMetadata>,
): FixResponse {
  const template = FIX_TEMPLATES[req.ruleId];
  if (template) {
    const result = template.generateFix(req.html, {
      html: req.html,
      target: undefined,
      failureSummary: req.failureSummary,
      parentHtml: req.parentHtml,
      childrenHtml: req.childrenHtml,
    });
    return {
      fixHtml: result.fixHtml,
      explanation: result.explanation,
      wcagCriteria: metadata?.wcag ?? [],
      techniques: [],
      failures: [],
      source: 'template',
      renderMode: req.mode ?? 'grounded_semantic',
    };
  }

  return {
    fixHtml: req.html,
    explanation: metadata?.description ?? `No fix available for rule "${req.ruleId}".`,
    wcagCriteria: metadata?.wcag ?? [],
    techniques: [],
    failures: [],
    source: 'template',
    renderMode: req.mode ?? 'grounded_semantic',
  };
}

async function callInsightsForViolation(req: FixRequest): Promise<InsightResponse> {
  return getInsights({
    axeResults: {
      violations: [
        {
          id: req.ruleId,
          description: getRuleMetadata(req.ruleId)?.description ?? req.ruleId,
          impact: getRuleMetadata(req.ruleId)?.impact,
          nodes: [
            {
              html: req.html,
              failureSummary: req.failureSummary,
              parentHtml: req.parentHtml,
              childrenHtml: req.childrenHtml,
              siblingHtml: req.siblingHtml,
              ...(req.checks ? { checks: req.checks } : {}),
            },
          ],
        },
      ],
    },
    url: req.url ?? 'unknown',
    // get_fix defaults to grounded_semantic; scan_and_fix overrides to
    // deterministic. Both skip the Path-A narrative (docs §8).
    mode: req.mode ?? 'grounded_semantic',
  }, { scanId: req.scanId });
}

async function callInsightsForExplain(ruleId: string, scanId?: string): Promise<InsightResponse> {
  const metadata = getRuleMetadata(ruleId);
  return getInsights({
    axeResults: {
      violations: [
        {
          id: ruleId,
          description: metadata?.description ?? ruleId,
          impact: metadata?.impact,
          nodes: [{ html: `<div data-rule="${ruleId}"></div>` }],
        },
      ],
    },
    url: 'explain-only',
    // Explanation only needs ontology criteria/techniques — skip Path A.
    mode: 'deterministic',
  }, { scanId });
}

function findGuidance(
  insights: InsightResponse,
  ruleId: string,
): ViolationGuidance | undefined {
  return insights.violationGuidance?.find((g) => g.violationId === ruleId);
}
